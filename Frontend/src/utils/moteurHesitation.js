/**
 * =========================================================
 * OUTILS
 * =========================================================
 */

const obtenirCodes = (reponses = []) => {

    return reponses
        .map((reponse) => reponse.code)
        .filter(Boolean);

};


const obtenirProfils = (codes) => {

    return codes
        .map((code) => profilsHesitation[code])
        .filter(Boolean);

};


const trouverCode = (codes, prefix) => {

    return codes.find((code) =>
        code.startsWith(prefix)
    );

};


/**
 * =========================================================
 * FORMULATION CONTEXTUELLE
 * =========================================================
 *
 * On adapte les formulations au type de choix.
 * Cela permet d'avoir une restitution différente pour
 * les métiers et les filières sans multiplier les règles.
 */

const contexteType = (typeChoix) => {

    if (typeChoix === "metier") {

        return {
            singulier: "métier",
            pluriel: "métiers",
            verbe: "exercer",
            expression:
                "les métiers que tu envisages"
        };

    }

    return {
        singulier: "filière",
        pluriel: "filières",
        verbe: "suivre",
        expression:
            "les filières que tu envisages"
    };

};


/**
 * =========================================================
 * SYNTHÈSE
 * =========================================================
 */

const genererSynthese = ({
    typeChoix,
    options,
    attirance,
    force,
    blocage,
    critere
}) => {

    const contexte = contexteType(typeChoix);

    const nombreOptions = options.length;

    let texte =
        `À partir de tes réponses, ton hésitation semble actuellement concerner ` +
        `${nombreOptions} ${contexte.pluriel}. `;


    /*
     * Plusieurs options
     */

    if (blocage?.axe === "multiples_options") {

        texte +=
            `Ce qui ressort surtout, c'est que plusieurs possibilités ` +
            `semblent déjà répondre à une partie de tes attentes. `;

    } else {

        texte +=
            `L'enjeu semble donc moins être de trouver un choix parfait ` +
            `que de comprendre ce qui distingue réellement ces possibilités ` +
            `pour ta situation actuelle. `;

    }


    /*
     * Attirance
     */

    if (attirance) {

        texte +=
            `Dans ta réflexion, tu sembles particulièrement attentif à ` +
            `${attirance.titre}. `;

    }


    /*
     * Force
     */

    if (force) {

        texte +=
            `Tes réponses font également ressortir une certaine aisance ` +
            `dans les situations liées à ${force.titre.toLowerCase()}. `;

    }


    /*
     * Blocage
     */

    if (blocage) {

        texte +=
            `Aujourd'hui, ce qui semble surtout compliquer la décision ` +
            `est ${blocage.titre.toLowerCase()}.`;

    }


    return texte;

};


/**
 * =========================================================
 * CONCLUSION
 * =========================================================
 */

const genererConclusion = ({
    typeChoix,
    attirance,
    force,
    blocage,
    critere,
    besoin
}) => {

    const contexte = contexteType(typeChoix);

    /*
     * Blocage : peur de se tromper
     */

    if (
        blocage?.axe === "peur_erreur" &&
        besoin?.axe === "rassurance"
    ) {

        return (
            `Tu ne sembles pas avoir besoin de choisir dans l'urgence. ` +
            `Tes réponses suggèrent plutôt que tu cherches à réduire ` +
            `le risque de regret avant de t'engager dans un ${contexte.singulier}. ` +
            `Une comparaison concrète des possibilités pourrait donc être ` +
            `plus utile qu'une recherche de certitude absolue.`
        );

    }


    /*
     * Plusieurs options + comparaison
     */

    if (
        blocage?.axe === "multiples_options" &&
        besoin?.axe === "comparaison"
    ) {

        return (
            `Le point important n'est probablement pas de déterminer ` +
            `quelle option est objectivement la meilleure, mais de comprendre ` +
            `laquelle répond le mieux à tes priorités actuelles. ` +
            `Une comparaison directe des ${contexte.pluriel} devrait ` +
            `t'aider à rendre cette différence plus visible.`
        );

    }


    /*
     * Manque d'information + réalité
     */

    if (
        blocage?.axe === "manque_information" &&
        besoin?.axe === "realite"
    ) {

        return (
            `Ton hésitation semble surtout venir d'un manque de visibilité ` +
            `sur ce que représentent concrètement tes options. ` +
            `Avant de chercher à trancher, il serait donc pertinent ` +
            `d'explorer la réalité du ${contexte.singulier}, les activités ` +
            `concernées et les compétences réellement mobilisées.`
        );

    }


    /*
     * Capacités + compatibilité
     */

    if (
        blocage?.axe === "doute_capacites" &&
        besoin?.axe === "compatibilite"
    ) {

        return (
            `Une partie de ta réflexion semble porter sur ta capacité ` +
            `à réussir dans les différentes possibilités. ` +
            `Plutôt que de tirer une conclusion définitive sur ton niveau, ` +
            `il serait plus utile de regarder quelles compétences sont ` +
            `réellement mobilisées et lesquelles tu pourrais développer.`
        );

    }


    /*
     * Débouchés
     */

    if (
        critere?.axe === "debouches" &&
        besoin?.axe === "debouches"
    ) {

        return (
            `Les perspectives professionnelles semblent avoir un poids ` +
            `important dans ta décision. ` +
            `Pour avancer, comparer les débouchés, les évolutions possibles ` +
            `et les réalités professionnelles associées à tes options ` +
            `pourrait t'aider à les départager.`
        );

    }


    /*
     * Conditions
     */

    if (
        critere?.axe === "conditions"
    ) {

        return (
            `Tes réponses montrent que le cadre dans lequel tu pourrais ` +
            `évoluer compte particulièrement dans ta réflexion. ` +
            `Il peut donc être pertinent de comparer les environnements, ` +
            `les conditions de travail et les modes d'exercice associés ` +
            `à chaque possibilité.`
        );

    }


    /*
     * Cas général riche
     */

    let conclusion =
        `Tes réponses donnent surtout des indications sur ce qui compte ` +
        `pour toi dans cette décision aujourd'hui. `;


    if (attirance) {

        conclusion +=
            `Tu sembles notamment sensible à ${attirance.titre}. `;

    }


    if (force) {

        conclusion +=
            `Tes réponses font également ressortir une certaine aisance ` +
            `dans les situations liées à ${force.titre.toLowerCase()}. `;

    }


    if (critere) {

        conclusion +=
            `Le critère qui semble actuellement peser le plus est ` +
            `${critere.titre.toLowerCase()}. `;

    }


    if (besoin) {

        conclusion +=
            `Pour avancer, tu pourrais surtout chercher ` +
            `${besoin.titre.toLowerCase()}.`;

    } else {

        conclusion +=
            `La prochaine étape peut simplement consister à mieux comprendre ` +
            `tes options avant de prendre une décision.`;

    }


    return conclusion;

};


/**
 * =========================================================
 * CONSEILS
 * =========================================================
 */

const genererConseils = ({
    typeChoix,
    blocage,
    critere,
    besoin
}) => {

    const contexte = contexteType(typeChoix);

    const conseils = [];


    /*
     * Conseil 1 : besoin principal
     */

    if (besoin?.axe === "comparaison") {

        conseils.push({
            titre: "Compare concrètement tes options",
            description:
                `Mets côte à côte les activités, les compétences mobilisées ` +
                `et les réalités de chaque ${contexte.singulier}.`
        });

    } else if (besoin?.axe === "compatibilite") {

        conseils.push({
            titre: "Pars de tes forces",
            description:
                `Observe quelles options utilisent les capacités dans lesquelles ` +
                `tu te sens le plus à l'aise.`
        });

    } else if (besoin?.axe === "realite") {

        conseils.push({
            titre: "Explore la réalité",
            description:
                `Va au-delà du nom du ${contexte.singulier} et regarde concrètement ` +
                `ce que l'on y fait et dans quel environnement.`
        });

    } else if (besoin?.axe === "debouches") {

        conseils.push({
            titre: "Regarde les perspectives",
            description:
                `Compare les débouchés, les évolutions possibles et les réalités ` +
                `professionnelles avant de départager tes options.`
        });

    } else {

        conseils.push({
            titre: "Clarifie ce qui compte vraiment",
            description:
                "Identifie les deux ou trois critères qui pourraient réellement " +
                "faire la différence entre tes options."
        });

    }


    /*
     * Conseil 2 : critère
     */

    if (critere?.axe === "interet") {

        conseils.push({
            titre: "Confronte ton intérêt à la réalité",
            description:
                `Vérifie que ce qui t'attire dans chaque ${contexte.singulier} ` +
                `correspond bien à ce que tu pourrais y vivre au quotidien.`
        });

    } else if (critere?.axe === "capacites") {

        conseils.push({
            titre: "Mets tes capacités en perspective",
            description:
                "Distingue ce que tu maîtrises déjà de ce que tu pourrais apprendre."
        });

    } else if (critere?.axe === "stabilite") {

        conseils.push({
            titre: "Observe la stabilité réelle",
            description:
                "Compare les perspectives et les conditions concrètes plutôt que " +
                "de te fier uniquement à l'image générale d'une option."
        });

    } else {

        conseils.push({
            titre: "Compare tes priorités",
            description:
                "Pour chaque option, demande-toi ce qu'elle apporte réellement " +
                "par rapport à tes priorités actuelles."
        });

    }


    /*
     * Conseil 3 : blocage
     */

    if (blocage?.axe === "peur_erreur") {

        conseils.push({
            titre: "Ne cherche pas la certitude absolue",
            description:
                "Une bonne décision n'est pas forcément une décision sans risque. " +
                "Cherche plutôt suffisamment d'informations pour avancer sereinement."
        });

    } else if (blocage?.axe === "manque_information") {

        conseils.push({
            titre: "Cherche des informations concrètes",
            description:
                `Explore les informations disponibles sur les ${contexte.pluriel} ` +
                `avant de tirer une conclusion.`
        });

    } else if (blocage?.axe === "influence_entourage") {

        conseils.push({
            titre: "Sépare tes critères de ceux des autres",
            description:
                "Écoute les avis extérieurs, mais identifie ce qui correspond réellement à tes propres priorités."
        });

    } else {

        conseils.push({
            titre: "Passe de la réflexion à l'exploration",
            description:
                `Utilise maintenant les informations concrètes disponibles ` +
                `pour confronter tes premières impressions à la réalité.`
        });

    }


    return conseils.slice(0, 3);

};


/**
 * =========================================================
 * MOTEUR PRINCIPAL
 * =========================================================
 */

export const genererAnalyseHesitation = ({
    typeChoix,
    metiersSelectionnes = [],
    filieresSelectionnees = [],
    reponsesHesitation = []
}) => {

    const codes = obtenirCodes(reponsesHesitation);

    const profils = obtenirProfils(codes);

    const attiranceCode =
        trouverCode(codes, "ATTIRANCE_");

    const forceCode =
        trouverCode(codes, "FORCE_");

    const blocageCode =
        trouverCode(codes, "BLOCAGE_");

    const critereCode =
        trouverCode(codes, "CRITERE_");

    const besoinCode =
        trouverCode(codes, "BESOIN_");

        const attirance =
        attiranceCode
            ? profilsHesitation[attiranceCode]
            : null;

    const force =
        forceCode
            ? profilsHesitation[forceCode]
            : null;

    const blocage =
        blocageCode
            ? profilsHesitation[blocageCode]
            : null;

    const critere =
        critereCode
            ? profilsHesitation[critereCode]
            : null;

    const besoin =
        besoinCode
            ? profilsHesitation[besoinCode]
            : null;


    const options =
        typeChoix === "metier"
            ? metiersSelectionnes
            : filieresSelectionnees;


    const synthese = genererSynthese({
        typeChoix,
        options,
        attirance,
        force,
        blocage,
        critere
    });


    const conclusion = genererConclusion({
        typeChoix,
        attirance,
        force,
        blocage,
        critere,
        besoin
    });


    const conseils = genererConseils({
        typeChoix,
        blocage,
        critere,
        besoin
    });


    return {

        typeChoix,

        options,

        codes,

        synthese,

        pointsForts:
            force
                ? [force]
                : [],

        attirance,

        blocage,

        critere,

        besoin,

        conclusion,

        conseils

    };

};